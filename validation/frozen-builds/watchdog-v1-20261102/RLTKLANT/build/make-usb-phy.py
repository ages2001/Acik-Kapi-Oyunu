#!/usr/bin/env python3
"""Extract pinned vendor PHY functions, preserving their bodies verbatim.

Linux allocation, URB and scheduling code is outside this translation unit.
The small compatibility boundary implements serialized, fallible register I/O.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/r8152/vendor-r8152.c'
SHA = '87397a44617a38ed21720cfd4b50f2dbaea263291f94915a18442ca846f7e7ca'
ROOTS = ['r8152b_hw_phy_cfg', 'r8153_hw_phy_cfg', 'r8153b_hw_phy_cfg',
         'r8153c_hw_phy_cfg', 'r8156_hw_phy_cfg', 'r8156b_hw_phy_cfg',
         'r8157_hw_phy_cfg', 'r8159_hw_phy_cfg']
ROOTS += ['r8152b_init','r8153_init','r8153b_init','r8153c_init',
          'r8156_init','r8156b_init','r8157_init','r8159_init']
ROOTS += ['rtl8152_up','rtl8153_up','rtl8153b_up','rtl8153c_up','rtl8156_up',
          'rtl8157_up','rtl8152_enable','rtl8153_enable','rtl8156_enable',
          'rtl8156b_enable','rtl8157_enable']
BOUNDARY = {'ocp_read_byte', 'ocp_read_word', 'ocp_read_dword',
            'ocp_write_byte', 'ocp_write_word', 'ocp_write_dword',
            'generic_ocp_read', 'generic_ocp_write', 'ocp_reg_read', 'ocp_reg_write'}
BUILTINS = {'if', 'for', 'while', 'switch', 'return', 'sizeof', 'ARRAY_SIZE',
            'BIT', 'WARN_ON_ONCE', 'clear_bit', 'set_bit', 'test_bit',
            'dev_dbg', 'dev_err', 'msleep', 'usleep_range', 'memset',
            'KERNEL_VERSION','device_set_wakeup_enable','usb_enable_lpm',
            'netif_dbg','hw_phy_cfg','test_and_clear_bit','ALIGN','WARN_ON',
            'max_t','min_t','netdev_reset_queue','netif_warn','skb_queue_len_lockless'}
CHECKED = {'r8153_phy_status', 'rtl_phy_patch_request', 'r8156b_wait_loading_flash',
           'r8153_wdt1_end', 'r8153_aldps_en', 'wait_adv_cmd_ready',
           'r8159_wait_backup_restore','rtl8152_nic_reset','wait_oob_link_list_ready'}

def masked(source):
    return re.sub(r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'',
                  lambda m: re.sub(r'[^\n]', ' ', m[0]), source, flags=re.S)

def generate():
    raw = SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA:
        raise ValueError('Vendor source changed; review the extraction before accepting it')
    source = raw.decode(); clean = masked(source); functions = {}
    for m in re.finditer(r'^static\s+[\w\s*]+?\b(\w+)\s*\([^;{}]*\)\s*\{', clean, re.M):
        depth = 1; end = m.end()
        while depth:
            depth += (clean[end] == '{') - (clean[end] == '}'); end += 1
        functions[m[1]] = (m.start(), m.end()-1, end)
    definitions = {}
    for m in re.finditer(r'^#define\s+(\w+)(?:[^\n]*\\\n)*[^\n]*', source, re.M):
        definitions.setdefault(m[1], []).append(m[0])
    selected = set(); external = set()
    def visit(name):
        if name in selected or name in BOUNDARY or name in BUILTINS: return
        if name not in functions:
            external.add(name); return
        selected.add(name); start, _, end = functions[name]
        for called in re.findall(r'\b(\w+)\s*\(', clean[start:end])[1:]: visit(called)
    for root in ROOTS: visit(root)
    if external - definitions.keys():
        raise ValueError('Unreviewed dependencies: ' + repr(external - definitions.keys()))
    ordered = sorted(selected, key=lambda f: functions[f][0])
    def declaration(f):
        a,b,_ = functions[f]
        return source[a:b].rstrip()
    def emitted(f):
        a,b,c = functions[f]
        header = source[a:b]
        if f in CHECKED: header = re.sub(r'\b'+f+r'\b', 'vendor_'+f, header, count=1)
        return header + source[b:c]
    body = '\n\n'.join(emitted(f) for f in ordered)
    names = set(re.findall(r'\b\w+\b', masked(body)))
    macros = {}
    while names:
        name = names.pop()
        if name in macros or name not in definitions: continue
        candidates = set(definitions[name])
        if len(candidates) != 1: raise ValueError('Conditional macro needs review: '+name)
        macros[name] = candidates.pop()
        names.update(re.findall(r'\b\w+\b', masked(macros[name])))
    enums = []
    for name in ('rtl_version', 'rtl8152_flags', 'rtl_register_content','adv_access_type','spd_duplex'):
        enums.append(re.search(r'enum '+name+r'\s*\{.*?\};', source, re.S)[0])
    notice = source[:source.index('#include')]
    head = notice + '\n/* Generated by build/make-usb-phy.py; do not edit. */\n'
    constants = head + '\n'.join(macros[n] for n in sorted(macros))+'\n\n'+'\n\n'.join(enums)+'\n'
    prototypes = '\n'.join(declaration(f)+';' for f in ordered)
    unit = head + prototypes + '\n\n' + body + '\n'
    provenance = {'repository': 'https://github.com/bb-qq/r8152',
                  'commit': '477a723a41c3340bd7d701f657711c334d0c42bd',
                  'source_sha256': SHA, 'license': 'GPL-2.0-only',
                  'checked_wrappers': sorted(CHECKED),
                  'changes': ['Rename listed function definitions, preserving bodies, to add checked postconditions in usbphyseq.c. Other function bodies and embedded arrays are unchanged.'],
                  'scope': 'PHY configuration, embedded vendor patches, MAC cold-init/up/enable. Separate from host power policy, packet queues and actual silicon validation.',
                  'functions': [{'name': f, 'line': source.count('\n',0,functions[f][0])+1,
                                 'sha256': hashlib.sha256(source[functions[f][0]:functions[f][2]].encode()).hexdigest()}
                                for f in ordered]}
    out = ROOT/'third_party/r8152'
    return {out/'phy-sequences.inc': unit, out/'phy-constants.h': constants,
            out/'PHY-PROVENANCE.json': json.dumps(provenance,indent=2)+'\n'}

if __name__ == '__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path, contents in generate().items():
        if args.check:
            if not path.exists() or path.read_text()!=contents: raise SystemExit('Stale generated file: '+str(path))
        else: path.write_text(contents)
    print('PASS: pinned USB PHY extraction' if args.check else 'Generated pinned USB PHY functions')
