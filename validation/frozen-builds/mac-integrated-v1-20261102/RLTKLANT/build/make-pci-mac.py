#!/usr/bin/env python3
"""Extract pinned r8169 MAC configuration bodies without Linux kernel ABI.

This component is separate from DMA publication, OS power policy and PHY setup.
The compatibility boundary must propagate every failed register transaction.
"""
from pathlib import Path
import argparse,hashlib,json,re
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'third_party/r8169/r8169_main.c'
SHA='cb918734e19369d22fd0e65657c0183518f0ba59b57745a74f6a5bbcf56f37cc'
ROOTS=['rtl_hw_config','rtl_hw_start_8125','rtl_hw_start_8168','rtl_hw_start_8169','__rtl_ephy_init','rtl_set_aspm_entry_latency','rtl8168ep_stop_cmac']
ROOTS += ['rtl_unlock_config_regs','rtl_lock_config_regs',
          'rtl_hw_aspm_clkreq_enable','rtl_set_eee_txidle_timer','rtl_enable_exit_l1']
BOUNDARY={'rtl_eri_read','rtl_eri_write','r8168_mac_ocp_read','r8168_mac_ocp_write','__r8168_mac_ocp_read','__r8168_mac_ocp_write','rtl_ephy_read','rtl_ephy_write','rtl_loop_wait_low','rtl_loop_wait_high'}
ENUMS=['rtl_registers','rtl8168_8101_registers','rtl8168_registers','rtl8125_registers','rtl_register_content']
def masked(s):
 return re.sub(r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'',lambda m:re.sub(r'[^\n]',' ',m[0]),s,flags=re.S)
def generate():
 raw=SOURCE.read_bytes();assert hashlib.sha256(raw).hexdigest()==SHA,'Review changed upstream source'
 s=raw.decode();clean=masked(s);functions={};conditions={}
 for m in re.finditer(r'^static\s+[\w\s*]+?\b(\w+)\s*\([^;{}]*\)\s*\{',clean,re.M):
  depth=1;end=m.end()
  while depth:depth+=(clean[end]=='{')-(clean[end]=='}');end+=1
  functions[m[1]]=(m.start(),m.end()-1,end)
 for m in re.finditer(r'^DECLARE_RTL_COND\((\w+)\)\s*\{',clean,re.M):
  depth=1;end=m.end()
  while depth:depth+=(clean[end]=='{')-(clean[end]=='}');end+=1
  conditions[m[1]]=(m.start(),end)
 selected=set();used_conditions=set()
 def visit(n):
  if n in selected or n in BOUNDARY:return
  assert n in functions,n
  selected.add(n);start,body,end=functions[n]
  for ident in set(re.findall(r'\b\w+\b',clean[body:end])):
   if ident in functions:visit(ident)
   if ident in conditions:used_conditions.add(ident)
 for n in ROOTS:visit(n)
 ordered=sorted(selected,key=lambda n:functions[n][0])
 notice=s[:s.index('#include')]
 head=notice+'\n/* Generated by build/make-pci-mac.py; do not edit. */\n'
 definitions={}
 for m in re.finditer(r'^#define\s+(\w+)(?:[^\n]*\\\n)*[^\n]*',s,re.M):definitions.setdefault(m[1],[]).append(m[0])
 body='\n\n'.join(s[functions[n][0]:functions[n][2]] for n in ordered)
 enums='\n\n'.join(re.search(r'enum '+n+r'\s*\{.*?\};',s,re.S)[0] for n in ENUMS)
 macros={};names=set(re.findall(r'\b\w+\b',masked(body+enums)))
 excluded={'RTL_R8','RTL_R16','RTL_R32','RTL_W8','RTL_W16','RTL_W32','DECLARE_RTL_COND'}
 while names:
  n=names.pop()
  if n in macros or n in excluded or n not in definitions:continue
  rows=set(definitions[n]);assert len(rows)==1,'Conditional macro needs review: '+n
  macros[n]=rows.pop();names.update(re.findall(r'\b\w+\b',masked(macros[n])))
 # Definitions nested inside enums/functions already remain in their original location.
 embedded=set(re.findall(r'^#define\s+(\w+)',body+enums,re.M))
 constants=head+'\n'.join(macros[n] for n in sorted(macros) if n not in embedded)+'\n'+enums+'\n'
 prototypes='\n'.join(s[functions[n][0]:functions[n][1]].rstrip()+';' for n in ordered)
 cond='\n\n'.join(s[conditions[n][0]:conditions[n][1]] for n in sorted(used_conditions))
 unit=head+prototypes+'\n\n'+cond+'\n\n'+body+'\n'
 provenance={'repository':'https://github.com/torvalds/linux','commit':'65ba8f34ec886ec72b2c07ddc8cf3d815c32869d','source_sha256':SHA,'license':'GPL-2.0-only','scope':'Verbatim MAC configuration subtree; separate from complete adapter initialization and lifecycle. Runtime integration and silicon validation are not implied.','roots':ROOTS,'boundary':sorted(BOUNDARY),'conditions':sorted(used_conditions),'functions':[{'name':n,'line':s.count('\n',0,functions[n][0])+1,'sha256':hashlib.sha256(s[functions[n][0]:functions[n][2]].encode()).hexdigest()} for n in ordered]}
 out=ROOT/'third_party/r8169';return {out/'mac-sequences.inc':unit,out/'mac-constants.h':constants,out/'MAC-PROVENANCE.json':json.dumps(provenance,indent=2)+'\n'}
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
 for path,contents in generate().items():
  if a.check:assert path.exists() and path.read_text()==contents,'Stale generated file: '+str(path)
  else:path.write_text(contents)
 print('PASS: pinned PCI MAC extraction' if a.check else 'Generated pinned PCI MAC configuration bodies')
